#!/usr/bin/env Rscript
# Generate R `twfeweights` parity goldens for the diff-diff TWFE weight diagnostics.
#
# Requires: twfeweights (>= 0.9.0, MIT, Brantly Callaway), did, fixest, BMisc,
#           DRDID, jsonlite
# Output:   benchmarks/data/twfeweights_golden.json
#           benchmarks/data/twfeweights_mpdta_panel.csv
#           benchmarks/data/twfeweights_sim_panel.csv
#           benchmarks/data/twfeweights_unbalanced_panel.csv
#
# Run from the repository root:
#   Rscript benchmarks/R/generate_twfeweights_golden.R
#
# ---------------------------------------------------------------------------
# WHAT THIS PINS
#
# `diff_diff/twfe_weights.py` exposes two entry points, each folding several
# upstream R functions:
#
#   attgt_weights(aggregation=)     <- twfe_weights / attO_weights /
#                                      att_simple_weights
#   decompose_twfe_weights(method=) <- implicit_twfe_weights /
#                                      implicit_aipw_weights
#
# plus covariate balance as a result-object method (<- twfe_cov_bal /
# aipw_cov_bal / mp_covariate_bal_summary_helper) and two private two-period
# kernels (<- two_period_reg_weights / two_period_aipw_weights) that are
# pinned here because they have no public Python surface of their own.
#
# ---------------------------------------------------------------------------
# NOTE (upstream bug — do NOT "simplify" the no-covariate calls below)
#
# twfeweights::implicit_twfe_weights() with xformula = ~1 (or NULL) builds
# model.matrix(BMisc::addCovToFormla("-1", ~1), data), an nT x 0 matrix, and
# fixest::demean() SEGFAULTS on a zero-column matrix. Reproduced in isolation
# on R 4.6.1 / fixest 0.14.2:
#
#     fixest::demean(matrix(numeric(0), nrow = 10, ncol = 0), ids)
#     *** caught segfault *** address ..., cause 'memory not mapped'
#
# This is a zero-column bug, NOT a conditioning problem with any particular
# fixture — every fixture hits it on the ~1 branch and no fixture hits it
# otherwise.
#
# The no-covariate decomposition is therefore generated by passing a
# TIME-INVARIANT covariate: double-demeaning annihilates such a regressor
# exactly, so the call is numerically identical to the ~1 branch. Verified on
# mpdta, where `lpop` is time-invariant within county:
#
#     twfe_weights(att_gt(...)) aggregate     = -0.03654894
#     implicit_twfe_weights(xformula = ~lpop) = -0.03654894   (exact)
#
# The Python parity test asserts BOTH covariates=None AND
# covariates=[<that column>] against this single golden, so the equivalence is
# proven by the test rather than assumed by the generator.
# ---------------------------------------------------------------------------

suppressPackageStartupMessages({
  library(twfeweights)
  library(did)
  library(jsonlite)
})

stopifnot(packageVersion("twfeweights") == "0.9.0")

# BMisc 1.4.9 emits .Deprecated warnings for makeBalancedPanel / addCovToFormla
# / getListElement on every internal call; they would otherwise flood the log.
quiet <- function(expr) suppressWarnings(suppressMessages(expr))

out_dir <- file.path("benchmarks", "data")
if (!dir.exists(out_dir)) {
  stop("run this script from the repository root (", out_dir, " not found)")
}

# ---------------------------------------------------------------------------
# Extraction helpers
#
# Field names below are read off the upstream S3 objects:
#   mp_weights_obj   $weights_df: group, time.period, weight, attgt, post
#   decomposed_twfe  $twfe_gt[[i]]: g, tp, weighted_outcome_diff (= ATT(g,t)),
#                                   alpha_weight, ess, remainder, cov_bal_df
#   decomposed_aipw  $aipw_gt[[i]]: g, tp, est (= ATT(g,t)), att_weight, ess
# The scalar roll-ups mirror summary.decomposed_twfe / summary.decomposed_aipw
# exactly (twfeweights_mp.R:337 and :995).
# ---------------------------------------------------------------------------

extract_mp_weights <- function(obj) {
  df <- obj$weights_df
  list(
    group = as.numeric(df$group),
    time = as.numeric(df$time.period),
    post = as.integer(df$post),
    weight = as.numeric(df$weight),
    att = as.numeric(df$attgt),
    implied_att = sum(df$weight * df$attgt)
  )
}

extract_fwl <- function(obj) {
  cells <- obj$twfe_gt
  g <- unlist(BMisc::getListElement(cells, "g"))
  tp <- unlist(BMisc::getListElement(cells, "tp"))
  att <- unlist(BMisc::getListElement(cells, "weighted_outcome_diff"))
  wt <- unlist(BMisc::getListElement(cells, "alpha_weight"))
  ess <- unlist(BMisc::getListElement(cells, "ess"))
  rem <- unlist(BMisc::getListElement(cells, "remainder"))
  post <- 1 * (tp >= g)
  list(
    cells = list(
      group = as.numeric(g), time = as.numeric(tp), post = as.integer(post),
      att = as.numeric(att), weight = as.numeric(wt),
      ess = as.numeric(ess), remainder = as.numeric(rem)
    ),
    estimate = obj$est,
    decomposition = obj$decomposition_est,
    remainder = obj$decomposition_remainder,
    pretrend_bias = obj$pt_violations_bias,
    post_only = sum(wt[post == 1] * att[post == 1]),
    # summary.decomposed_twfe:351
    effective_sample_size = sum(post) * sum(wt[post == 1] * ess[post == 1])
  )
}

extract_aipw <- function(obj) {
  cells <- obj$aipw_gt
  g <- unlist(BMisc::getListElement(cells, "g"))
  tp <- unlist(BMisc::getListElement(cells, "tp"))
  att <- unlist(BMisc::getListElement(cells, "est"))
  wt <- unlist(BMisc::getListElement(cells, "att_weight"))
  ess <- unlist(BMisc::getListElement(cells, "ess"))
  post <- 1 * (tp >= g)
  list(
    cells = list(
      group = as.numeric(g), time = as.numeric(tp), post = as.integer(post),
      att = as.numeric(att), weight = as.numeric(wt), ess = as.numeric(ess)
    ),
    estimate = obj$est,
    decomposition = obj$decomposition_est,
    remainder = obj$decomposition_remainder,
    pretrend_bias = obj$pt_violations_bias,
    post_only = sum(wt[post == 1] * att[post == 1]),
    # summary.decomposed_aipw:1006 — note the inner sum is NOT post-filtered,
    # unlike the twfe roll-up. Preserved verbatim.
    effective_sample_size = sum(post) * sum(wt * ess)
  )
}

# Per-cell balance tables, one row per (g, t) x covariate.
extract_balance_cells <- function(cells) {
  g <- unlist(BMisc::getListElement(cells, "g"))
  tp <- unlist(BMisc::getListElement(cells, "tp"))
  dfs <- BMisc::getListElement(cells, "cov_bal_df")
  rows <- do.call(rbind.data.frame, lapply(seq_along(dfs), function(i) {
    d <- dfs[[i]]
    cbind.data.frame(
      group = g[i], time = tp[i], post = 1 * (tp[i] >= g[i]),
      covariate = rownames(d), d, row.names = NULL
    )
  }))
  as.list(lapply(rows, function(col) if (is.character(col)) col else as.numeric(col)))
}

extract_balance_summary <- function(cells) {
  s <- quiet(mp_covariate_bal_summary_helper(cells))
  out <- as.list(lapply(s, as.numeric))
  out$covariate <- rownames(s)
  out
}

extract_two_period <- function(obj) {
  list(
    estimate = as.numeric(obj$est),
    ess = if (is.null(obj$ess)) NA_real_ else as.numeric(obj$ess),
    weights = as.numeric(obj$weights),
    dy = as.numeric(obj$dy),
    treatment = as.numeric(obj$D)
  )
}

# ---------------------------------------------------------------------------
# Per-fixture golden bundle
#
# `invariant_cov` must be TIME-INVARIANT within unit — it drives the
# no-covariate branch (see the segfault note at the top).
# `varying_cov` must be genuinely time-varying, so the covariate-adjusted
# weights differ from the unadjusted ones.
# ---------------------------------------------------------------------------

build_fixture <- function(df, data_file, outcome, unit, time, first_treat,
                          invariant_cov, varying_cov, two_period_g) {
  stopifnot(all(tapply(df[[invariant_cov]], df[[unit]],
                       function(z) length(unique(z))) == 1))

  # Slice the two-period sub-panel FIRST. Several upstream entry points
  # (did::att_gt, and BMisc helpers reached from implicit_*) call
  # data.table::setDT() on the frame they are handed, which converts it BY
  # REFERENCE — after that, `df[cond, ]` silently takes data.table semantics
  # and errors. Taking the subset up front sidesteps the whole problem.
  tp_periods <- c(two_period_g - 1, two_period_g)
  sub <- as.data.frame(df)[df[[time]] %in% tp_periods &
                             df[[first_treat]] %in% c(0, two_period_g), ]

  ag <- quiet(att_gt(
    yname = outcome, tname = time, idname = unit, gname = first_treat,
    xformla = ~1, data = df, control_group = "nevertreated",
    base_period = "universal", bstrap = FALSE
  ))
  # did::att_gt calls data.table::setDT(data), which converts the caller's
  # frame BY REFERENCE. Everything below assumes data.frame `[` semantics, so
  # convert back explicitly rather than relying on what att_gt left behind.
  df <- as.data.frame(df)

  inv_f <- as.formula(paste0("~", invariant_cov))
  var_f <- as.formula(paste0("~", varying_cov))
  bal_f <- as.formula(paste0("~", invariant_cov, "+", varying_cov))

  common <- list(yname = outcome, tname = time, idname = unit,
                 gname = first_treat, data = df)

  fwl_nocov <- quiet(do.call(implicit_twfe_weights,
                             c(common, list(xformula = inv_f))))
  fwl_cov <- quiet(do.call(implicit_twfe_weights,
                           c(common, list(xformula = var_f))))
  fwl_gmin1 <- quiet(do.call(implicit_twfe_weights,
                             c(common, list(xformula = inv_f,
                                            base_period = "gmin1"))))
  aipw <- quiet(do.call(implicit_aipw_weights,
                        c(common, list(xformula = inv_f))))

  # Balance is taken off the COVARIATE-ADJUSTED decomposition: on the
  # no-covariate branch the implicit weights are constant within the treated
  # and comparison groups, so weighted == unweighted and the table is
  # degenerate (verified). fwl_cov gives a non-trivial reweighting.
  bal_fwl <- quiet(twfe_cov_bal(fwl_cov, bal_f))
  bal_aipw <- quiet(aipw_cov_bal(aipw, bal_f))

  # Two-period kernels: the (g = two_period_g) cohort against never-treated,
  # over periods {g-1, g}. These are private in Python, so this is the only
  # place they are pinned. (`sub` was sliced at the top of this function.)
  sub_common <- list(yname = outcome, tname = time, idname = unit,
                     gname = first_treat, data = sub)
  tp_reg <- quiet(do.call(two_period_reg_weights,
                          c(sub_common, list(xformula = var_f))))
  tp_aipw <- quiet(do.call(two_period_aipw_weights,
                           c(sub_common, list(xformula = var_f))))

  list(
    data_file = data_file,
    columns = list(outcome = outcome, unit = unit, time = time,
                   first_treat = first_treat,
                   invariant_cov = invariant_cov, varying_cov = varying_cov),
    two_period_group = two_period_g,
    attgt_weights = list(
      twfe = extract_mp_weights(quiet(twfe_weights(ag))),
      overall = extract_mp_weights(quiet(attO_weights(ag))),
      simple = extract_mp_weights(quiet(att_simple_weights(ag)))
    ),
    decompose = list(
      fwl_nocov = extract_fwl(fwl_nocov),
      fwl_cov = extract_fwl(fwl_cov),
      fwl_gmin1 = extract_fwl(fwl_gmin1),
      aipw = extract_aipw(aipw)
    ),
    balance = list(
      fwl = list(cells = extract_balance_cells(bal_fwl$twfe_gt),
                 summary = extract_balance_summary(bal_fwl$twfe_gt)),
      aipw = list(cells = extract_balance_cells(bal_aipw$aipw_gt),
                  summary = extract_balance_summary(bal_aipw$aipw_gt))
    ),
    two_period = list(reg = extract_two_period(tp_reg),
                      aipw = extract_two_period(tp_aipw))
  )
}

# ---------------------------------------------------------------------------
# Fixture 1 — mpdta (real data)
#
# did::mpdta: 500 US counties x 2003-2007, cohorts {2004, 2006, 2007} plus
# never-treated (first.treat == 0), time-invariant `lpop`. Also exercises
# non-1..T time labels, which the Python side handles by positional rescaling.
# ---------------------------------------------------------------------------

data(mpdta, package = "did")
mpdta_df <- data.frame(
  unit = as.numeric(mpdta$countyreal),
  period = as.numeric(mpdta$year),
  first_treat = as.numeric(mpdta$first.treat),
  outcome = as.numeric(mpdta$lemp),
  lpop = as.numeric(mpdta$lpop)
)
mpdta_df <- mpdta_df[order(mpdta_df$unit, mpdta_df$period), ]
# `lpop` is time-invariant; build a genuinely time-varying companion from it so
# the covariate-adjusted branch is non-degenerate on this fixture too.
mpdta_df$lpop_t <- mpdta_df$lpop * (mpdta_df$period - 2002) / 5

# ---------------------------------------------------------------------------
# Fixture 2 — sim_staggered (simulated)
#
# Well-conditioned by construction: 3 equal cohorts of 100 so no (g,t) cell is
# degenerate and 100 controls per cell keep the AIPW propensity score bounded
# away from 0/1; `0.3 * x1 * period` induces a REAL pre-trend so
# pretrend_bias != 0 and the diagnostic is not testing a trivial zero.
# ---------------------------------------------------------------------------

make_sim <- function(seed, cohort_sizes, cohort_times, n_periods) {
  set.seed(seed)
  n <- sum(cohort_sizes)
  g <- rep(cohort_times, times = cohort_sizes)
  x1 <- rnorm(n)
  unit_fe <- rnorm(n)
  df <- do.call(rbind, lapply(seq_len(n_periods), function(t) {
    data.frame(unit = seq_len(n), period = t, first_treat = g,
               x1 = x1, unit_fe = unit_fe)
  }))
  df <- df[order(df$unit, df$period), ]
  df$xtv <- 0.2 * df$period + 0.5 * df$x1 + rnorm(nrow(df), 0, 0.5)
  treated <- (df$first_treat != 0) & (df$period >= df$first_treat)
  df$outcome <- df$unit_fe + 0.5 * df$period + 0.3 * df$x1 * df$period +
    1.0 * treated * (df$period - df$first_treat + 1) + rnorm(nrow(df))
  df$unit_fe <- NULL
  rownames(df) <- NULL
  df
}

sim_df <- make_sim(20260831, c(100, 100, 100), c(0, 3, 4), 5)

# ---------------------------------------------------------------------------
# Fixture 3 — unbalanced_cohorts
#
# Fixture 2 has equal thirds, so p_g == 1/3 and several of the weight formulas
# coincide — a bug in the cohort-share computation would pass silently there.
# Unequal cohort masses (120 / 70 / 60) break that degeneracy. Do not drop this
# fixture.
# ---------------------------------------------------------------------------

unb_df <- make_sim(20260901, c(120, 70, 60), c(0, 3, 5), 6)

# ---------------------------------------------------------------------------
# Build + write
# ---------------------------------------------------------------------------

write.csv(mpdta_df, file.path(out_dir, "twfeweights_mpdta_panel.csv"),
          row.names = FALSE)
write.csv(sim_df, file.path(out_dir, "twfeweights_sim_panel.csv"),
          row.names = FALSE)
write.csv(unb_df, file.path(out_dir, "twfeweights_unbalanced_panel.csv"),
          row.names = FALSE)

cat("building mpdta ...\n")
fx_mpdta <- build_fixture(mpdta_df, "twfeweights_mpdta_panel.csv",
                          "outcome", "unit", "period", "first_treat",
                          "lpop", "lpop_t", two_period_g = 2004)
cat("building sim_staggered ...\n")
fx_sim <- build_fixture(sim_df, "twfeweights_sim_panel.csv",
                        "outcome", "unit", "period", "first_treat",
                        "x1", "xtv", two_period_g = 3)
cat("building unbalanced_cohorts ...\n")
fx_unb <- build_fixture(unb_df, "twfeweights_unbalanced_panel.csv",
                        "outcome", "unit", "period", "first_treat",
                        "x1", "xtv", two_period_g = 3)

payload <- list(
  meta = list(
    description = paste(
      "R twfeweights parity goldens for diff_diff attgt_weights /",
      "decompose_twfe_weights. Regenerate with:",
      "Rscript benchmarks/R/generate_twfeweights_golden.R"
    ),
    upstream = paste(
      "twfeweights (Brantly Callaway), MIT License,",
      "Copyright (c) 2023 Brantly Callaway"
    ),
    r_version = paste(R.version$major, R.version$minor, sep = "."),
    twfeweights_version = as.character(packageVersion("twfeweights")),
    did_version = as.character(packageVersion("did")),
    fixest_version = as.character(packageVersion("fixest")),
    BMisc_version = as.character(packageVersion("BMisc")),
    DRDID_version = as.character(packageVersion("DRDID")),
    seeds = list(sim_staggered = 20260831L, unbalanced_cohorts = 20260901L),
    no_covariate_note = paste(
      "decompose.fwl_nocov is generated with xformula = ~<time-invariant col>,",
      "which is numerically the ~1 branch (double-demeaning annihilates a",
      "time-invariant regressor exactly). The ~1 branch itself cannot be",
      "called: fixest::demean segfaults on the zero-column model matrix it",
      "builds. See the comment block at the top of the generator."
    )
  ),
  fixtures = list(
    mpdta = fx_mpdta,
    sim_staggered = fx_sim,
    unbalanced_cohorts = fx_unb
  )
)

out_path <- file.path(out_dir, "twfeweights_golden.json")
write_json(payload, out_path, auto_unbox = TRUE, digits = NA, pretty = TRUE)
cat("wrote", out_path, "\n")
cat("  mpdta twfe implied_att      =", fx_mpdta$attgt_weights$twfe$implied_att, "\n")
cat("  mpdta fwl_nocov estimate    =", fx_mpdta$decompose$fwl_nocov$estimate, "\n")
cat("  sim   fwl_nocov estimate    =", fx_sim$decompose$fwl_nocov$estimate, "\n")
cat("  unb   twfe implied_att      =", fx_unb$attgt_weights$twfe$implied_att, "\n")
