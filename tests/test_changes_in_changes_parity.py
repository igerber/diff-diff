FIXTURE_PATH = Path(__file__).parent.parent / "benchmarks" / "data" / "qte_golden.json"

POINT_ATOL = 1e-10
COV_ATT_ATOL = 0.04
COV_QTE_ATOL = 0.25
QTE_VERSION = "1.3.1"
QUANTREG_VERSION = "6.1"


def _load_fixture():
    if not FIXTURE_PATH.exists():
        pytest.skip(
            f"Golden fixture {FIXTURE_PATH} missing - regenerate via "
            f"`Rscript benchmarks/R/generate_qte_golden.R`."
        )
    with open(FIXTURE_PATH) as f:
        return json.load(f)


@pytest.fixture(scope="module")
def fixture():
    return _load_fixture()


@pytest.fixture(scope="module")
def probs(fixture):
    # Use the R-stored probs doubles: R's seq() and np.arange() can differ in
    # trailing ulps, and the quantile index arithmetic is sensitive to them.
    return np.asarray(fixture["metadata"]["probs"], dtype=float)


def _scenario_df(scenario):
    return pd.DataFrame({k: scenario["data"][k] for k in ("id", "period", "treat", "y")})


def _fit(df, method, mode, probs, n_bootstrap=0, seed=None, covariates=None):
    cls = ChangesInChanges if method == "cic" else QDiD
    est = cls(
        quantiles=probs,
        n_bootstrap=n_bootstrap,
        panel=(mode == "panel"),
        seed=seed,
    )
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        return est.fit(
            df,
            outcome="y",
            treatment="treat",
            time="period",
            unit="id" if mode == "panel" else None,
            covariates=covariates,
        )


def _as_list(x):
    """jsonlite auto_unbox collapses single-element vectors to scalars."""
    return x if isinstance(x, list) else [x]


