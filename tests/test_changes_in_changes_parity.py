class TestSEStatisticalParity:
    """Scheme-identical bootstrap SEs agree statistically (never bit-exactly:
    qte's bootstrap is unseeded through its public API, so the R draws cannot
    be replicated; both sides estimate the SD of the same resampling scheme)."""

    @pytest.mark.parametrize("block_key", ["cic_panel", "cic_rcs", "qdid_panel", "qdid_rcs"])
    def test_se_parity(self, fixture, probs, ci_params, block_key):
        block = fixture["se_block"].get(block_key)
        if block is None:
            pytest.skip(f"se_block {block_key} missing from fixture")
        scenario = fixture["scenarios"]["normal_2x2_n500"]
        method, mode = block_key.rsplit("_", 1)

        n_boot = ci_params.bootstrap(499, min_n=199)
        res = _fit(_scenario_df(scenario), method, mode, probs, n_bootstrap=n_boot, seed=42)

        # ATT SE: repo convention threshold.
        att_threshold = 0.40 if n_boot < 100 else 0.15
        r_ate_se = float(block["ate_se"])
        rel = abs(res.se - r_ate_se) / r_ate_se
        assert rel < att_threshold, (
            f"{block_key}: ATT SE rel diff {rel:.3f} vs R "
            f"({res.se:.5f} vs {r_ate_se:.5f}, n_boot={n_boot})"
        )

        # Per-quantile SEs: looser bound - tail-quantile bootstrap SEs are
        # noisier than the ATT SE at any replicate count.
        qte_threshold = 0.40 if n_boot < 100 else 0.25
        r_qte_se = np.asarray(block["qte_se"], dtype=float)
        py_qte_se = res.quantile_effects["se"].to_numpy()
        rel_q = np.abs(py_qte_se - r_qte_se) / r_qte_se
        assert np.nanmax(rel_q) < qte_threshold, (
            f"{block_key}: worst per-quantile SE rel diff {np.nanmax(rel_q):.3f} "
            f"(n_boot={n_boot})"
        )

    @pytest.mark.slow
    @pytest.mark.parametrize("block_key", ["cic_cov_panel", "qdid_cov_rcs"])
    def test_se_parity_covariates(self, fixture, probs, ci_params, block_key):
        """Covariate-path bootstrap SE parity (slow: every replicate refits
        2-3 x 99 quantile-regression LPs, so ~199 replicates take ~1-2 min
        regardless of the Rust backend - hence the smaller min_n than the
        documented min_n=199 convention, with the <100-replicate 0.40
        threshold absorbing the extra noise). Vertex/knot tie-selection
        differences (see header) contribute variance far below these
        statistical thresholds.
        """
        block = fixture["se_block"].get(block_key)
        if block is None:
            pytest.skip(f"se_block {block_key} missing from fixture")
        scenario = fixture["scenarios"][block["scenario"]]
        covariates = _as_list(block["covariates"])
        method, _, mode = block_key.split("_")
        df = pd.DataFrame({k: scenario["data"][k] for k in scenario["data"]})

        n_boot = ci_params.bootstrap(199, min_n=99)
        res = _fit(df, method, mode, probs, n_bootstrap=n_boot, seed=42, covariates=covariates)

        att_threshold = 0.40 if n_boot < 100 else 0.15
        r_ate_se = float(block["ate_se"])
        rel = abs(res.se - r_ate_se) / r_ate_se
        assert rel < att_threshold, (
            f"{block_key}: ATT SE rel diff {rel:.3f} vs R "
            f"({res.se:.5f} vs {r_ate_se:.5f}, n_boot={n_boot})"
        )

        qte_threshold = 0.40 if n_boot < 100 else 0.25
        r_qte_se = np.asarray(block["qte_se"], dtype=float)
        py_qte_se = res.quantile_effects["se"].to_numpy()
        rel_q = np.abs(py_qte_se - r_qte_se) / r_qte_se
        assert np.nanmax(rel_q) < qte_threshold, (
            f"{block_key}: worst per-quantile SE rel diff {np.nanmax(rel_q):.3f} "
            f"(n_boot={n_boot})"
        )

    def test_sup_t_crit_loose_parity(self, fixture, probs, ci_params):
        """The sup-t critical value is a bootstrap quantile - compare loosely."""
        block = fixture["se_block"].get("cic_panel")
        if block is None:
            pytest.skip("se_block cic_panel missing from fixture")
        scenario = fixture["scenarios"]["normal_2x2_n500"]
        n_boot = ci_params.bootstrap(499, min_n=199)
        res = _fit(_scenario_df(scenario), "cic", "panel", probs, n_bootstrap=n_boot, seed=42)
        r_c = float(block["sup_t_crit"])
        assert np.isfinite(res.sup_t_crit)
