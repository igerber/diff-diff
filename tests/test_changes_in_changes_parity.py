"""R-parity golden-fixture tests for ChangesInChanges (CiC) and QDiD vs qte 1.3.1.

Fixture: benchmarks/data/qte_golden.json, generated by
benchmarks/R/generate_qte_golden.R (qte pinned to 1.3.1 and quantreg to 6.1
there and in benchmarks/R/requirements.R). Point fixtures were generated with
se=FALSE and are deterministic; the se_block was generated seeded
(set.seed(42), iters=999, cores=1 - qte's default cores=2 forks and is NOT
reproducible even seeded) and is compared statistically since bootstrap draws
cannot be replicated across languages.

Tolerances:
- POINT_ATOL = 1e-10 for unconditional end-to-end ATT/QTE values (means and
  type-7 interpolation differ from R by ~1 ulp; type-1 selections are
  bit-exact).
- Covariate (xformla) end-to-end values are TIE-SELECTION-BOUNDED, not
  ~1e-10: (i) the QR check loss can have a non-trivial optimal face and the
  two exact solvers (R br simplex, scipy HiGHS) then select different
  vertices with identical loss; (ii) R's Fhat knots are often EXACTLY tied
  across adjacent taus (shared interpolating basis) and predict.rqs orders
  ties by tau index, while Python's ~1e-15-different predictions break the
  ties by value - so a share of conditional ranks legitimately lands a grid
  step away. Both are selections among equally valid solutions. Hence:
  COV_ATT_ATOL / COV_QTE_ATOL are empirical tie-flip bounds: the committed
  fixtures measure worst 9.3e-3 / 8.1e-2 on this platform, and a 30-dataset
  randomized decomposition audit (5 DGP families incl. binary-covariate and
  ties-heavy cells; 2026-07-13) observed same-mechanism deviations up to
  3.5e-2 / 0.40 on adversarial data - the gates carry cross-platform margin
  because a different BLAS can flip DIFFERENT ties on the same fixture data,
  while a real composition bug errs at O(0.5-1). The audit's invariants:
  composition-on-R-coefficients exact 30/30 (worst 1.3e-15), 8910 LP solves
  all coefficient-matching or two-sided loss-equal (worst gap 3.2e-16, zero
  descent-probe failures), all 1586 rank flips attributed to the documented
  tie mechanisms, no directional bias (sign tests p=0.69/0.59). The
  CONVENTIONS are pinned at atol=0 by the qr_cases tests conditioned on R's
  stored coefficients/predictions, and the LP solver is proven exactly
  optimal per tau (equal coefficients OR equal check loss).
- Micro-fixtures: type-1 quantiles at atol=0 (pure order-statistic selection,
  bit-exact cross-language); type-7 at rtol=1e-15 (R's (1-h)*lo + h*hi vs
  numpy's lerp differ in the last ulp).
- SE parity: threshold = 0.40 if n_boot < 100 else 0.15 for the ATT SE and
  0.25 per-quantile (tail-quantile bootstrap SEs are noisier at any replicate
  count; both sides estimate the same scheme-identical bootstrap SD).
"""

import json
import warnings
from pathlib import Path

import numpy as np
