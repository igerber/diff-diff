SCENARIOS_COV = ["cov1_2x2_n300", "cov2_2x2_n240"]
RESULT_KEYS_COV = ["cic_cov_panel", "cic_cov_rcs", "qdid_cov_panel", "qdid_cov_rcs"]


@pytest.mark.parametrize("scenario_name", SCENARIOS_COV)
@pytest.mark.parametrize("result_key", RESULT_KEYS_COV)
def test_covariate_point_parity(fixture, probs, scenario_name, result_key):
    """End-to-end covariate parity at the tie-selection bounds (see header)."""
    scenario = fixture["scenarios"].get(scenario_name)
    if scenario is None:
        pytest.skip(f"Scenario {scenario_name} missing from fixture")
    golden = scenario["results"][result_key]
    method, _, mode = result_key.split("_")
    covariates = _as_list(scenario["covariates"])
    df = pd.DataFrame({k: scenario["data"][k] for k in scenario["data"]})

    res = _fit(df, method, mode, probs, covariates=covariates)

    np.testing.assert_allclose(res.att, golden["ate"], atol=COV_ATT_ATOL, rtol=0)
    qte_diff = np.abs(
        res.quantile_effects["qte"].to_numpy() - np.asarray(golden["qte"], dtype=float)
    )
    np.testing.assert_allclose(qte_diff, 0.0, atol=COV_QTE_ATOL, rtol=0)
    # Sharpness floor: tie-selection only perturbs the handful of quantiles
    # whose rank lookup lands in a knot-tie group / degenerate-vertex region -
    # the REST must agree with R at machine precision. Measured tight counts
    # (this platform): CiC 17 and 15 of 19; QDiD 6 and 3 of 19 (own-cell ranks
    # are structurally knot-exact, so QDiD flips more; the randomized audit
    # confirms QDiD flips heavily on adversarial data). Floors sit well below
    # measured so a different BLAS/HiGHS build flipping different ties cannot
    # fail them, while a real composition bug (all 19 off) still does.
    min_tight = 10 if method == "cic" else 1
    n_tight = int(np.sum(qte_diff < 1e-8))
    assert n_tight >= min_tight, (
        f"{scenario_name}/{result_key}: only {n_tight}/19 quantiles within 1e-8 of R "
        f"(sharpness floor {min_tight}) - deviations are broader than tie-selection."
    )
    assert res.covariates == covariates
    assert np.isnan(res.q_lower) and np.isnan(res.q_upper)


class TestQRCases:
    """Convention anchors for the covariate branch, conditioned on R's stored
    intermediates so tie-selection cannot blur them (see the header docstring):
    the Fhat/Qhat step-function lookups and both estimators' compositions must
    be BIT-EXACT given R's stored prediction matrices, the dot products must
    match R's to the last ulp given R's coefficients, and the LP solver must
    be exactly optimal at every tau.
    """

    @staticmethod
    def _cells(case):
        covs = _as_list(case["covariates"])
        out = {}
        for ck, blk in case["cells"].items():
            out[ck] = {
                "y": np.asarray(blk["y"], dtype=float),
                "X": np.column_stack([np.asarray(blk[c], dtype=float) for c in covs]),
            }
        return out

    def test_predictions_match_given_r_coefficients(self, fixture):
        # Isolates dot-product arithmetic from step-function conventions.
        # Last-ulp tolerance rather than exact equality: 2-3-term dot products
        # are observed bit-identical to R on this platform, but BLAS/FMA
        # reassociation can differ by an ulp elsewhere (assert_allclose
        # convention for float linalg). The step-function convention tests
        # below stay exact - they consume R's STORED prediction matrices, so
        # no floating-point arithmetic sits between fixture and assertion.
        for name, case in fixture["qr_cases"].items():
            cells = self._cells(case)
            x10d = _design_matrix(cells["c10"]["X"])
            for cell_key, pred_key in (
                ("c00", "preds00_at_x10"),
                ("c01", "preds01_at_x10"),
                ("c10", "preds10_at_x10"),
            ):
                coef_r = np.asarray(case[f"coef{cell_key[1:]}"], dtype=float)
                np.testing.assert_allclose(
                    x10d @ coef_r,
                    np.asarray(case[pred_key], dtype=float),
                    rtol=1e-15,
                    atol=1e-300,
                    err_msg=f"prediction mismatch in '{name}' cell {cell_key}",
                )

    def test_fhat_qhat_conventions_bit_exact_given_r_predictions(self, fixture):
        # The predict.rqs Fhat/Qhat step-function ports and both compositions,
        # conditioned on R's prediction matrices: atol=0.
        for name, case in fixture["qr_cases"].items():
            cells = self._cells(case)
            y10 = cells["c10"]["y"]
            preds = {
                k: np.asarray(case[k], dtype=float)
                for k in ("preds00_at_x10", "preds01_at_x10", "preds10_at_x10")
            }
            ranks_cic = _fhat_eval(preds["preds00_at_x10"], _QR_TAU_GRID, y10)
            np.testing.assert_array_equal(
                ranks_cic,
                np.asarray(case["cic_ranks"], dtype=float),
                err_msg=f"CiC ranks mismatch in '{name}'",
            )
            y0t_cic = _qhat_eval(preds["preds01_at_x10"], _QR_TAU_GRID, ranks_cic)
            np.testing.assert_array_equal(
                y0t_cic,
                np.asarray(case["cic_y0t"], dtype=float),
                err_msg=f"CiC imputations mismatch in '{name}'",
            )
            ranks_qdid = _fhat_eval(preds["preds10_at_x10"], _QR_TAU_GRID, y10)
            np.testing.assert_array_equal(
                ranks_qdid,
                np.asarray(case["qdid_ranks"], dtype=float),
                err_msg=f"QDiD ranks mismatch in '{name}'",
            )
            y0t_qdid = (
                y10
                + _qhat_eval(preds["preds01_at_x10"], _QR_TAU_GRID, ranks_qdid)
                - _qhat_eval(preds["preds00_at_x10"], _QR_TAU_GRID, ranks_qdid)
            )
            np.testing.assert_array_equal(
                y0t_qdid,
                np.asarray(case["qdid_y0t"], dtype=float),
                err_msg=f"QDiD imputations mismatch in '{name}'",
            )

    def test_micro_end_to_end_consistent_with_stored_qte_outputs(self, fixture):
        # Guards against qte's internals diverging from raw predict.rqs usage:
        # composing R's STORED imputations into ATT/QTE with the module's
        # quantile helpers must reproduce the stored qte::CiC()/QDiD() outputs
        # (R-vs-R consistency - no solver or tie-selection freedom involved,
        # so the tolerance is arithmetic-tight).
        for name, case in fixture["qr_cases"].items():
            cells = self._cells(case)
            y11_sorted = np.sort(cells["c11"]["y"])
            y0t_cic = np.asarray(case["cic_y0t"], dtype=float)
            att_cic = float(np.mean(cells["c11"]["y"]) - np.mean(y0t_cic))
            probs = np.asarray(fixture["metadata"]["probs"], dtype=float)
            qte_cic = _quantile_type1(y11_sorted, probs) - _quantile_type1(np.sort(y0t_cic), probs)
            np.testing.assert_allclose(att_cic, case["cic_ate"], atol=1e-12, rtol=0)
            np.testing.assert_allclose(
                qte_cic,
                np.asarray(case["cic_qte"], dtype=float),
                atol=1e-12,
                rtol=0,
                err_msg=f"CiC micro end-to-end inconsistency in '{name}'",
            )
            y0t_qdid = np.asarray(case["qdid_y0t"], dtype=float)
            att_qdid = float(np.mean(cells["c11"]["y"]) - np.mean(y0t_qdid))
            qte_qdid = _quantile_type7(y11_sorted, probs) - _quantile_type1(
                np.sort(y0t_qdid), probs
            )
            np.testing.assert_allclose(att_qdid, case["qdid_ate"], atol=1e-12, rtol=0)
            np.testing.assert_allclose(
                qte_qdid,
                np.asarray(case["qdid_qte"], dtype=float),
                atol=1e-12,
                rtol=0,
                err_msg=f"QDiD micro end-to-end inconsistency in '{name}'",
            )

    def test_rq_fit_exactly_optimal_per_tau(self, fixture):
        # Two-sided optimality criterion: at every tau, either the
        # coefficients match R's (unique-vertex case, ~1e-14 observed) or the
        # check losses match to relative 1e-10 (non-trivial optimal face -
        # structural for qr2's binary covariate - where both solvers return
        # exact but different vertices).
        for name, case in fixture["qr_cases"].items():
            cells = self._cells(case)
            for cell_key in ("c00", "c01", "c10"):
                y = cells[cell_key]["y"]
                x_design = _design_matrix(cells[cell_key]["X"])
                coef_r = np.asarray(case[f"coef{cell_key[1:]}"], dtype=float)  # (k+1) x 99
                coef_py = _rq_fit(y, cells[cell_key]["X"], _QR_TAU_GRID)
                assert coef_py is not None, f"LP failed in '{name}' cell {cell_key}"
                for j, tau in enumerate(_QR_TAU_GRID):
                    if np.max(np.abs(coef_py[j] - coef_r[:, j])) < 1e-8:
                        continue
                    resid_r = y - x_design @ coef_r[:, j]
                    resid_py = y - x_design @ coef_py[j]
                    loss_r = np.sum(np.where(resid_r >= 0, tau * resid_r, (tau - 1) * resid_r))
                    loss_py = np.sum(np.where(resid_py >= 0, tau * resid_py, (tau - 1) * resid_py))
                    assert abs(loss_py - loss_r) <= 1e-10 * max(abs(loss_r), 1.0), (
                        f"'{name}' cell {cell_key} tau={tau:.4f}: coefficients differ "
                        f"AND losses differ (R {loss_r!r} vs Py {loss_py!r}) - the "
                        "solver is suboptimal, not merely tie-breaking."
                    )


