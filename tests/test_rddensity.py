def _moment_g_minus(p: int, kernel: str) -> np.ndarray:
    """Test-local minus-side Gamma over (-1, 0) with the minus basis,
    computed by direct closed-form integration (no production `_minus`
    helper exists - R builds every minus-side matrix by Psi-conjugation)."""
    # substitute u -> -u: Gamma_minus[i, j] over (-1,0) equals the (0,1)
    # integral of the reflected integrand; integrate directly instead via
    # the identity-free route: G^-[i,j] = int_{-1}^0 k(-y)... To stay
    # independent of the reflection identity under test, integrate the
    # minus-side double integral numerically at high resolution.
    from scipy import integrate as _si

    kpoly = _KERNEL_POLY_01[kernel]

    def k(u):
        return _poly_eval(kpoly, abs(u))

    out = np.empty((p + 1, p + 1))
    for i in range(p + 1):
        for j in range(p + 1):

            def inner(y, _i=i, _j=j):
                lo, _ = _si.quad(lambda u: u ** (_i + 1) * k(u), -1.0, y, epsabs=1e-13)
                hi, _ = _si.quad(lambda u: u**_i * k(u), y, 0.0, epsabs=1e-13)
                return k(y) * (y**_j * lo + y ** (_j + 1) * hi)

            val, _ = _si.quad(inner, -1.0, 0.0, epsabs=1e-12, limit=200)
            out[i, j] = val
    return out


class TestMethodology:
    @pytest.mark.parametrize("kernel", ["triangular", "epanechnikov", "uniform"])
    @pytest.mark.parametrize("p", [1, 2, 3, 4, 5, 6, 7])
    def test_reflection_identity_generators(self, p, kernel):
        """SA proof 7.17: Gamma_minus = Psi Gamma_plus Psi + the two
        rank-one corrections (generator-level check of our closed-form
        integrators; INDEPENDENT of the variance path, which - matching R
        and SA Lemma 13 - uses the uncorrected Psi Gamma_plus Psi)."""
        if p > 4 and kernel != "triangular":
            pytest.skip("high-order quadrature reference kept to one kernel")
        g_plus = _embed_plus(_moment_g(p, kernel), p)
        s_plus = _embed_plus(_moment_s(p, kernel), p)
        psi = _psi_matrix(p)
        e0 = np.zeros(p + 2)
        e0[0] = 1.0
        e1m = np.zeros(p + 2)
        e1m[1] = 1.0
        # SA 7.17: Gamma_- = Psi Gamma_+ Psi + S_- e1- e0' S_- + S_- e0 e1-' S_-
        s_minus = psi @ s_plus @ psi
        expected = (
            psi @ g_plus @ psi
            + s_minus @ np.outer(e1m, e0) @ s_minus
            + s_minus @ np.outer(e0, e1m) @ s_minus
        )
        # reference minus-side Gamma via independent quadrature, embedded
        g_minus_raw = _moment_g_minus(p, kernel)
        g_minus = np.zeros((p + 2, p + 2))
        g_minus[0, 0] = g_minus_raw[0, 0]
        g_minus[0, 1] = g_minus_raw[0, 1]
        g_minus[1, 0] = g_minus_raw[1, 0]
        g_minus[1, 1] = g_minus_raw[1, 1]
        if p > 1:
            g_minus[0, 3:] = g_minus_raw[0, 2:]
            g_minus[3:, 0] = g_minus_raw[2:, 0]
            g_minus[1, 3:] = g_minus_raw[1, 2:]
            g_minus[3:, 1] = g_minus_raw[2:, 1]
            g_minus[3:, 3:] = g_minus_raw[2:, 2:]
        np.testing.assert_allclose(g_minus, expected, atol=5e-9)

    def test_joint_vs_separate_rescaling(self):
        """Under the rank EDF (0:(N-1))/(N-1), a separate per-side fit (the
        side's own EDF on a plain one-sided basis) equals the joint fit's
        side times (N-1)/(n_side - 1) - EXACTLY, because the interleaved
        joint basis is block-diagonal across sides and regression is linear
        in the regressand. The CJM paper's n/n_side factors instead apply to
        the paper's (1/n)*sum EDF, which neither R nor this port implements
        (the distinction is documented in the result docstring)."""
        rng = np.random.default_rng(7)
        x = np.sort(rng.normal(size=600))
        n = len(x)
        n_left = int(np.sum(x < 0))
        hl, hr = 0.6, 0.7
        q = 3
        y = np.arange(n) / (n - 1)
        w = (x >= -hl) & (x <= hr)
        xw, yw = x[w], y[w]
        n_lh = int(np.sum(xw < 0))
        joint = _rddensity_fv(
            yw,
            xw,
            n,
            n_lh,
            len(xw) - n_lh,
            hl,
            hr,
            q,
            1,
            "triangular",
            "unrestricted",
            "jackknife",
            False,
        )

        # separate left fit: the left subsample's own rank EDF on a plain
        # one-sided polynomial basis with the same kernel window
        left_sample = x[x < 0]
        y_sep = np.arange(n_left) / (n_left - 1)
        in_win = left_sample >= -hl
        u = left_sample[in_win] / hl
        design = np.column_stack([u**k for k in range(q + 1)])
        wts = (1.0 + u) / hl
        dw = design * wts[:, None]
        beta = np.linalg.solve(dw.T @ design, dw.T @ y_sep[in_win])
        f_sep_left = beta[1] / hl  # slope coefficient, unscaled

        factor = (n - 1) / (n_left - 1)
        assert f_sep_left == pytest.approx(joint[0, 0] * factor, rel=1e-12)
        # and the paper's n/n_left factor demonstrably differs
        assert f_sep_left != pytest.approx(joint[0, 0] * n / n_left, rel=1e-6)

    def test_affine_equivariance(self):
        rng = np.random.default_rng(11)
        x = rng.normal(size=1500)
        df1 = pd.DataFrame({"x": x})
        df2 = pd.DataFrame({"x": 3.5 * x + 10.0})
        r1 = _fit_quiet(RDDensityTest(cutoff=0.0), x)
        r2 = _fit_quiet(RDDensityTest(cutoff=10.0), 3.5 * x + 10.0)
        assert r1.t_stat == pytest.approx(r2.t_stat, rel=1e-9)
        # p = 2*Phi(-|t|) inherits the t-stat's relative error amplified by
        # 2*|t|*phi(|t|)/p (~5.9x at this seed's |t|~2.26), so its tolerance
        # must sit above the t-stat's or BLAS-kernel rounding differences
        # across CI runners can trip it (run #3384: rel diff 1.15e-9 on
        # ubuntu py3.14 only).
        assert r1.p_value == pytest.approx(r2.p_value, rel=1e-8)
        # densities scale by 1/s
        assert r1.f_left == pytest.approx(r2.f_left * 3.5, rel=1e-9)
        assert df1 is not df2

