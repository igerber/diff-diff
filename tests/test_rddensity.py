# The golden pipeline chains the bandwidth selector (two pilot fits at
# orders p and p+2), the window trim, and the order-q estimation - float
# noise accumulates across the chain, so the global parity bar is 1e-8
# (eight significant digits; the rdplot/rdrobust 1e-9 precedent applies to
# single un-chained fits).
RTOL = 1e-8

# Conditioning-limited configs (each stays as a correct-at-its-conditioning
# anchor; 1e-9 parity is mathematically unattainable there):
# - dgp_normal/p7: the selector's pilot fit runs at order p+2=9 (Gram
#   condition ~1e15), so the SELECTED bandwidth is only reproducible to
#   ~1e-5 relative across BLAS implementations, and that drift propagates
#   to every downstream quantity.
# - the nUniqueMin=0 floor configs on the tied fixtures: with the unique-
#   value floor disabled the selector runs on a tiny tied window whose
#   pilot quantities carry ~1e-8 relative float noise (floors_0_0 and
#   floors_50_0 are numerically the same selector run where the nLocalMin
#   gate does not bind).
RTOL_OVERRIDES = {
    ("dgp_normal", "p7"): 2e-3,
    ("dgp_masspoints", "floors_0_0"): 1e-7,
    ("dgp_masspoints", "floors_50_0"): 1e-7,
    ("dgp_masspoints_small", "floors_0_0"): 1e-7,
    ("dgp_masspoints_small", "floors_50_0"): 1e-7,
}


