    def test_conventional_inference_data_driven_bandwidth_warns(self):
        # CJM 2020 Section 4: the conventional order-p test over-rejects at
        # the MSE-optimal bandwidth. R reports the numbers silently; the
        # port keeps the R-parity values (golden-pinned) but warns whenever
        # conventional inference meets a DATA-DRIVEN bandwidth
        rng = np.random.default_rng(79)
        df = pd.DataFrame({"x": rng.normal(size=1200)})
        # q == p: the headline itself is the conventional fit
        with pytest.warns(UserWarning, match="over-rejects"):
            res_qp = RDDensityTest(p=2, q=2).fit(df, running="x")
        assert np.isfinite(res_qp.p_value)  # R-parity values stand
        # report_all: the conventional block at the selected bandwidth
        with pytest.warns(UserWarning, match="over-rejects"):
            res_all = RDDensityTest(report_all=True).fit(df, running="x")
        assert np.isfinite(res_all.p_value_conventional)
        # manual h: undersmoothing is the caller's responsibility - silent
        for est in (
            RDDensityTest(p=2, q=2, h=0.8),
            RDDensityTest(report_all=True, h=0.8),
        ):
            with warnings.catch_warnings(record=True) as caught:
                warnings.simplefilter("always")
                est.fit(df, running="x")
            assert not any("over-reject" in str(w.message) for w in caught)

    @pytest.mark.parametrize("kernel", ["triangular", "epanechnikov"])
    @pytest.mark.parametrize("vce", ["jackknife", "plugin"])
    def test_boundary_zero_weight_rank_deficiency_fails_loud(self, kernel, vce):
        # points sitting EXACTLY at the bandwidth boundary get kernel weight
        # 0 under triangular/epanechnikov (and the regularization range
        # clamp hits |x| = h exactly), so a side with order+1 unique values
        # but one of them at the boundary is rank deficient - R's
        # solve(tol=0) returns finite garbage; the weight-aware
        # unique-support guard raises instead
        left_vals = np.array([-1.0, -0.5, -0.3, -0.1])
        right_vals = np.array([0.1, 0.35, 0.6, 1.0])
        x = np.concatenate([np.repeat(left_vals, 10), np.repeat(right_vals, 10)])
        df = pd.DataFrame({"x": x})
        # default p=2 -> the robust fit runs at order q=3, needing 4
        # positive-weight unique values per side; the boundary point leaves 3
        with pytest.raises(ValueError, match="unique running-variable value"):
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                RDDensityTest(h=1.0, kernel=kernel, vcov_type=vce, masspoints="off").fit(
                    df, running="x"
                )
        # the uniform kernel keeps positive weight at the boundary: the same
        # design is genuinely full rank and must still fit
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            res = RDDensityTest(h=1.0, kernel="uniform", vcov_type=vce, masspoints="off").fit(
                df, running="x"
            )
        assert np.isfinite(res.f_diff)

