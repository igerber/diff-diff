def _num(value):
    """jsonlite writes NA as the string 'NA' (and NaN as null)."""
    if value is None or value == "NA":
        return np.nan
    return float(value)


def _estimator_from_args(args) -> RDDensityTest:
    """Rebuild RDDensityTest(...) from the golden config's R-args echo."""
    h = args.get("h")
    if isinstance(h, list):
        h = tuple(h)
    return RDDensityTest(
        cutoff=args["c"],
        p=args["p"],
        q=None if args["q"] == 0 else args["q"],
        fitselect=args["fitselect"],
        kernel=args["kernel"],
        vcov_type=args["vce"],
        h=h,
        bwselect=args["bwselect"],
        masspoints="adjust" if args["massPoints"] else "off",
        regularize=args["regularize"],
        n_local_min=args.get("nLocalMin"),
        n_unique_min=args.get("nUniqueMin"),
        report_all=args["all"],
    )


def _fit_quiet(est: RDDensityTest, x: np.ndarray) -> RDDensityTestResult:
    df = pd.DataFrame({"x": x})
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        return est.fit(df, running="x")


def _section_x(golden, section: str) -> np.ndarray:
    entry = golden[section]
    if "x" in entry:
        return np.asarray(entry["x"], dtype=float)
    csv = Path(__file__).resolve().parents[1] / entry["csv"]
    if not csv.exists():
        pytest.skip(f"vendored data file {entry['csv']} not found")
    col = pd.read_csv(csv)[entry["column"]]
    return col.dropna().to_numpy(dtype=float)


def _iter_configs(golden):
    for section, entry in golden.items():
        if section == "metadata":
            continue
        for name, cfg in entry["configs"].items():
            yield section, name, cfg


