    def test_aweight_clustered_hc2_bm_rejects(self):
        rng = np.random.default_rng(101)
        n, k = 30, 3
        X = np.column_stack([np.ones(n), rng.normal(size=(n, k - 1))])
        y = X @ np.array([1.0, 0.5, 0.3]) + rng.normal(0, 0.5, n)
        w = rng.uniform(0.5, 2.0, n)
