            compute_robust_vcov(
                X,
                y - X @ np.linalg.solve(X.T @ (X * w[:, None]), X.T @ (w * y)),
                cluster_ids=cluster_ids,
                vcov_type="hc2_bm",
                weights=w,
                weight_type="aweight",
            )

