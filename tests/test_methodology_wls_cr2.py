class TestWLSCR2ZeroWeightClusterRejection:
    """Zero-total-weight clusters (subpopulation-style padding) must NOT pass
    the `G>=2` check when only one effective cluster remains. Addresses Codex
    P1 finding."""

    def test_clustered_with_one_zero_weight_cluster_raises(self):
        """A weighted CR2 fit where one cluster has all-zero weights and only
        one other cluster has positive weight must raise."""
        rng = np.random.default_rng(201)
        n = 20
        X = np.column_stack([np.ones(n), rng.normal(size=n), rng.normal(size=n)])
        y = X @ np.array([1.0, 0.5, 0.3]) + rng.normal(0, 0.5, n)
        # Two clusters: 0 (positive weight) and 1 (all-zero weight).
        cluster_ids = np.array([0] * 10 + [1] * 10)
        w = np.concatenate([np.ones(10), np.zeros(10)])  # only cluster 0 has weight
        bread = X.T @ (X * w[:, None])
        # `bread_inv` would be rank-deficient if all-zero rows reduce design,
        # but we can ensure positive bread by adding a third tiny-weight cluster.
        cluster_ids = np.array([0] * 10 + [1] * 10)
        # Reformulate: 2 unique clusters but only 1 has positive total weight
        # (cluster 1 has w=0 for all its members).
        coef = np.linalg.solve(bread, X.T @ (w * y))
        resid = y - X @ coef
        with pytest.raises(ValueError, match="positive total weight"):
            _compute_cr2_bm(X, resid, cluster_ids, bread, weights=w)

    def test_contrast_dof_clustered_with_one_zero_weight_cluster_raises(self):
        """Same check for the contrast-DOF helper."""
        rng = np.random.default_rng(202)
        n = 20
        X = np.column_stack([np.ones(n), rng.normal(size=n), rng.normal(size=n)])
        X @ np.array([1.0, 0.5, 0.3]) + rng.normal(0, 0.5, n)
        cluster_ids = np.array([0] * 10 + [1] * 10)
        w = np.concatenate([np.ones(10), np.zeros(10)])
        bread = X.T @ (X * w[:, None])
        contrasts = np.eye(X.shape[1])
        with pytest.raises(ValueError, match="positive total weight"):
            _compute_cr2_bm_contrast_dof(X, cluster_ids, bread, contrasts, weights=w)

    def test_clustered_zero_weight_cluster_drops_silently_when_eff_clusters_remain(self):
        """A zero-weight cluster amongst multiple positive-weight clusters
        should be silently dropped (its scores contribute zero anyway). No raise."""
        rng = np.random.default_rng(203)
        # 4 clusters, last one zero-weight; should silently drop and use 3.
        cluster_ids = np.array([0] * 5 + [1] * 5 + [2] * 5 + [3] * 5)
        n = len(cluster_ids)
        X = np.column_stack([np.ones(n), rng.normal(size=n), rng.normal(size=n)])
        y = X @ np.array([1.0, 0.5, 0.3]) + rng.normal(0, 0.5, n)
        w = np.concatenate([np.ones(5), np.ones(5) * 1.5, np.ones(5) * 0.8, np.zeros(5)])
        bread = X.T @ (X * w[:, None])
        coef = np.linalg.solve(bread, X.T @ (w * y))
        resid = y - X @ coef
        vcov, dof = _compute_cr2_bm(X, resid, cluster_ids, bread, weights=w)
        assert np.all(np.isfinite(vcov)) and np.all(np.diag(vcov) > 0)
        assert np.all(np.isfinite(dof)) and np.all(dof > 0)


class TestLinearRegressionWeightedClusterHC2BM:
    """Regression for the R2 P0: `LinearRegression(vcov_type="hc2_bm")` on a
    weighted clustered fit must report Satterthwaite DOF via `_bm_dof`, not
    fall back to `n - k`. The previous skip in `fit()` left `_bm_dof = None`
    on the weighted-cluster branch, so `get_inference()` silently used the
    generic DOF and produced anti-conservative p-values / CIs."""

    def test_lr_weighted_cluster_hc2_bm_df_matches_helper(self):
        """`LinearRegression.get_inference()` df must match
        `compute_robust_vcov(..., return_dof=True)` DOF, not `n - k`."""
        from diff_diff.linalg import LinearRegression, compute_robust_vcov

        rng = np.random.default_rng(301)
        n = 40
        X = np.column_stack([np.ones(n), rng.normal(size=n), rng.normal(size=n)])
        cluster_ids = np.arange(n) % 8  # 8 clusters
        y = X @ np.array([1.0, 0.5, 0.3]) + rng.normal(0, 0.5, n)
        w = rng.uniform(0.5, 2.0, n)

        # Helper-level: directly compute the Satterthwaite DOF
        coef = np.linalg.solve(X.T @ (X * w[:, None]), X.T @ (w * y))
        resid = y - X @ coef
        _, helper_dof = compute_robust_vcov(
            X,
            resid,
            cluster_ids=cluster_ids,
            vcov_type="hc2_bm",
            weights=w,
            weight_type="pweight",
            return_dof=True,
        )

        # Public surface: fit through LinearRegression. weights/cluster live
        # on the constructor (not fit()), and the constructor needs
        # include_intercept=False because X already has an intercept column.
        lr = LinearRegression(
            include_intercept=False,
            vcov_type="hc2_bm",
            cluster_ids=cluster_ids,
            weights=w,
            weight_type="pweight",
        )
        lr.fit(X, y)
        # The Satterthwaite DOF must be threaded into get_inference(), NOT the
        # n-k fallback. Helper DOF should be small (cluster-driven); fallback
        # would be ~37 (n - k = 40 - 3).
        # _bm_dof is the internal attribute populated by fit() and consumed by
        # get_inference(); also check per-coefficient inference for thread.
        assert lr._bm_dof is not None, (
            "LinearRegression must populate _bm_dof on weighted-cluster path "
            "(previous code skipped this branch)"
        )
        np.testing.assert_allclose(
            lr._bm_dof,
            helper_dof,
            atol=1e-10,
            err_msg="_bm_dof must match helper Satterthwaite DOF",
        )
        # Sanity: cluster-driven DOF should be much smaller than n - k.
        assert np.all(np.asarray(lr._bm_dof) < n - X.shape[1]), (
            f"Expected cluster-driven Satterthwaite DOF << n-k={n - X.shape[1]}, "
            f"got {lr._bm_dof}"
        )
        # End-to-end: get_inference for each coefficient yields the right df.
        for i in range(X.shape[1]):
            inf_i = lr.get_inference(index=i)
            assert (
                inf_i.df == lr._bm_dof[i]
            ), f"get_inference(index={i}).df should equal _bm_dof[{i}]"

