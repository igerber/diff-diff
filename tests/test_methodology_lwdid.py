        r_cl = LWDiD(rolling="demean", estimation_method="reg", cluster="cl").fit(
            df, outcome="y", unit="unit", time="time", treatment="treat"
        )
        r_un = LWDiD(rolling="demean", estimation_method="reg", vcov_type="hc1").fit(
            df, outcome="y", unit="unit", time="time", treatment="treat"
        )
        assert r_cl.cluster_name == "cl"
        assert r_cl.n_clusters == 10
        # strong within-cluster correlation must MATERIALLY widen the SE,
        # not merely change it (a silent-HC1 implementation with metadata
        # would fail here; measured ratio ~2.7 on this fixture)
        assert r_cl.se > 1.15 * r_un.se, (r_cl.se, r_un.se)
        # ... and the value itself must equal the CR1 sandwich on the
        # collapsed cross-section, small-sample factor G/(G-1)*(N-1)/(N-K)
        # (verified identical to the contribution head's clustered path)
