    @pytest.mark.parametrize(
        "outcome",
        ["log_retail_emp", "log_wholesale_emp"],
        ids=["retail", "wholesale"],
    )
    @pytest.mark.parametrize("rolling,method", [("detrend", "reg")])
    def test_walmart_eventstudy_se_vs_stata(self, stata_golden, es_fit, rolling, method, outcome):
        """Bootstrap SEs vs the authors' Stata high-B multiplier bootstrap
        (RA config ONLY - the verified-equivalent scheme).

        Both sides are FIXED-rep Monte Carlo estimates of the same bootstrap
        SD, so the tolerance is the 4-sigma SE-of-SE bound
        ``4*sqrt(1/(2*B_py) + 1/(2*B_stata))`` (4-sigma because the bound is
        applied elementwise; at 3-sigma the family-wise chance of one MC
        excursion across all rows is ~40%). Any failure = STOP and
        investigate a scheme divergence; never widen this tolerance.

        The IPWRA configs are deliberately NOT gated here: measured
        2026-08-16, their bootstrap SEs diverge SYSTEMATICALLY from Stata's
        (~15% at row level, far beyond the MC bound) - the known SE-form
        difference (the contribution's IPWRA influence functions are
        AIPW-style, not the papers' E.3 stacked form that Stata implements).
        The Stata IPWRA SE columns stay in the golden as provenance; gating
        them awaits the E.3 IF-form adjudication on the PR #588 work list.
        """
        stata_method = {"reg": "ra", "dr": "ipwra"}[method]
        key = f"{rolling}_{stata_method}__{outcome}"
        table = stata_golden["walmart"][key]["watt"]
        r_stata = stata_golden["meta"]["bootstrap_reps"]
        rtol = 4 * np.sqrt(1 / (2 * 999) + 1 / (2 * r_stata))
        res = es_fit(rolling, method, outcome=outcome)
        for r in sorted(res.event_study_effects):
            cell = table.get(str(r))
            assert cell is not None and cell[1] is not None, f"{key} r={r} missing"
            np.testing.assert_allclose(
                res.event_study_effects[r]["se"], cell[1], rtol=rtol, err_msg=f"{key} r={r}"
            )

