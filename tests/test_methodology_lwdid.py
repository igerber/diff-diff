class TestExactSmallSampleInference:
    """The collapsed cross-sectional regression carries exact t inference."""

    def test_classical_p_value_uses_t_n_minus_2(self):
        df = _synthetic_common_timing(n_treat=6, n_control=10, t_max=6, s=4)
        res = LWDiD(rolling="demean", estimation_method="reg", vcov_type="classical").fit(
            df, outcome="y", unit="unit", time="time", treatment="treat"
        )
        n = df["unit"].nunique()
        p_expected = 2 * stats.t.sf(abs(res.t_stat), n - 2)
        np.testing.assert_allclose(res.p_value, p_expected, rtol=1e-10)

    def test_covariate_exact_inference_is_design_coherent(self):
        """Covariate-adjusted exact inference must be DESIGN-COHERENT.

        LW 2026 Section 2 sanctions two controlled collapsed regressions:
        the plain-controls design ``(1, D, X)`` with exact reference
        T_{N-K-2}, and the interacted design ``(1, D, X, D(X - Xbar_1))``
        whose design rank implies T_{N-2K-2} (with the per-group sample
        guards). Either is admissible; what is NOT is mixing them - fitting
        one design while reporting the other design's df gives
        anti-conservative exact p-values. MEASURED on the contribution head
        2026-08-16: the fitted att reproduces the INTERACTED design exactly
        while the p-value uses the plain design's T_{N-K-2} (df 19 vs the
        coherent 18 on a N=22, K=1 panel) - a required fix. This test
        identifies which design produced the point estimate and requires the
        p-value to use THAT design's residual df.
        """
        df = _synthetic_common_timing(n_treat=8, n_control=14, t_max=6, s=4)
        res = LWDiD(rolling="demean", estimation_method="reg", vcov_type="classical").fit(
            df, outcome="y", unit="unit", time="time", treatment="treat", covariates=["x"]
        )
        ybar = _demean_reference(df, "unit", "time", "y", pre_end=3)
        d = df.groupby("unit")["treated_group"].first().loc[ybar.index].to_numpy(dtype=float)
        xv = df.groupby("unit")["x"].first().loc[ybar.index].to_numpy(dtype=float)
        y = ybar.to_numpy(dtype=float)
        plain = np.column_stack([np.ones_like(d), d, xv])
        xbar_treated = xv[d == 1].mean()
        interacted = np.column_stack([np.ones_like(d), d, xv, d * (xv - xbar_treated)])
        n = len(y)
        matches = {}
        for name, X in (("plain", plain), ("interacted", interacted)):
            beta, *_ = np.linalg.lstsq(X, y, rcond=None)
            matches[name] = (abs(float(beta[1]) - res.att) < 1e-10, X.shape[1])
        matched = [name for name, (hit, _) in matches.items() if hit]
        assert len(matched) == 1, f"att matches designs: {matched or 'none'}"
        n_params = matches[matched[0]][1]
        p_expected = 2 * stats.t.sf(abs(res.t_stat), n - n_params)
        np.testing.assert_allclose(res.p_value, p_expected, rtol=1e-10)

    def test_single_treated_unit_inference_is_finite(self):
        """N1 = 1: exact inference remains valid (studentized-residual t)."""
        df = _synthetic_common_timing(n_treat=1, n_control=12, t_max=6, s=4)
