        cl_ids = df.groupby("unit")["cl"].first().loc[ybar.index].to_numpy()
        y = ybar.to_numpy(dtype=float)
        X = np.column_stack([np.ones_like(d), d])
        beta, *_ = np.linalg.lstsq(X, y, rcond=None)
        e = y - X @ beta
        n_units, k = X.shape
        n_cl = len(np.unique(cl_ids))
        bread = np.linalg.inv(X.T @ X)
        meat = np.zeros((k, k))
        for g_id in np.unique(cl_ids):
            m = cl_ids == g_id
            s = X[m].T @ e[m]
            meat += np.outer(s, s)
        factor = (n_cl / (n_cl - 1)) * ((n_units - 1) / (n_units - k))
        se_cr1 = float(np.sqrt((factor * bread @ meat @ bread)[1, 1]))
        np.testing.assert_allclose(r_cl.se, se_cr1, rtol=1e-10)

