    def test_fpc_shrinks_se(self, survey_golden: dict, survey_panel: pd.DataFrame) -> None:
        """A finite FPC shrinks the SE vs no-FPC, and the no-FPC path also matches svyglm.
        Both SEs are independently pinned to svyglm, so this checks the FPC mechanism
        end-to-end through the library, not just the golden."""
        sd_fpc = SurveyDesign(weights="weight", strata="stratum", psu="psu", fpc="fpc")
        sd_nofpc = SurveyDesign(weights="weight", strata="stratum", psu="psu")
        res_fpc = self._fit(survey_panel, sd_fpc)
        res_nofpc = self._fit(survey_panel, sd_nofpc)
        # the no-FPC path is itself svyglm-validated
        self._assert_es(res_nofpc, survey_golden["survey_vw_nofpc_es"], strata=True)
        se_fpc = {
            int(r.horizon): float(r.se)
            for r in res_fpc.event_study.itertuples()
            if np.isfinite(r.se)
        }
        se_nofpc = {
            int(r.horizon): float(r.se)
            for r in res_nofpc.event_study.itertuples()
            if np.isfinite(r.se)
        }
        assert se_fpc and se_fpc.keys() == se_nofpc.keys()
        for h in se_fpc:
            assert (
                se_fpc[h] < se_nofpc[h]
            ), f"FPC should shrink the SE at h={h}: {se_fpc[h]} !< {se_nofpc[h]}"

    def test_weighting_moves_point(self, survey_panel: pd.DataFrame) -> None:
        """The survey-weighted headline point differs from the unweighted VW point, so
        the probability weights demonstrably flow into the WLS estimate (not ignored)."""
        sd = SurveyDesign(weights="weight", strata="stratum", psu="psu", fpc="fpc")
        res_survey = self._fit(survey_panel, sd)
        res_unweighted = LPDiD(pre_window=3, post_window=4, reweight=False, cluster="unit").fit(
            survey_panel, outcome="y", unit="unit", time="time", treatment="treat"
        )
        assert abs(float(res_survey.att) - float(res_unweighted.att)) > 1e-3
