def _es_map(res) -> dict:
    return {
        int(r.horizon): (float(r.coefficient), float(r.se)) for r in res.event_study.itertuples()
    }


def _num(v) -> float:
    """Coerce a golden cell (number, JSON null, or a stray ``"NA"`` string) to float;
    any non-numeric value becomes NaN so the missing-value branch fires instead of a
    ``TypeError`` from calling ``np.isfinite`` on a non-number."""
    try:
        return float(v)
    except (TypeError, ValueError):
        return float("nan")


def _assert_es(ours: dict, golden_es: dict, *, check_se: bool = True) -> None:
    """Every golden horizon must be present and finite in ours, no silent skips."""
    assert golden_es, "golden variant has no horizons"
    for hk, gv in golden_es.items():
        h = int(hk)
        assert h in ours, f"missing horizon {h}"
        o_att, o_se = ours[h]
        g_att = _num(gv[0])
        if not np.isfinite(g_att):
            # NaN-consistency: a missing golden horizon requires BOTH our att and se NaN
            # (the library's all-inference-fields-NaN-together contract), not just att.
            assert not np.isfinite(o_att) and not np.isfinite(
                o_se
            ), f"h={h}: golden att NA but ours not fully NaN (att={o_att}, se={o_se})"
            continue
        assert np.isfinite(o_att), f"h={h}: non-finite att"
        assert o_att == pytest.approx(g_att, abs=1e-6), f"att h={h}"
        if check_se:
            g_se = _num(gv[1])
            if not np.isfinite(g_se):
                assert not np.isfinite(o_se), f"h={h}: golden se NA but ours finite"
            else:
                assert np.isfinite(o_se), f"h={h}: non-finite se"
                assert o_se == pytest.approx(g_se, abs=1e-7), f"se h={h}"


def _window(golden: dict):
    return golden["meta"]["pre_window"], golden["meta"]["post_window"]


def test_assert_es_tolerates_missing_golden_horizons() -> None:
    """A missing golden cell (JSON null, stray 'NA' string, or NaN) is handled as an
    empty-result horizon - consistent when ours is also NaN, a failure when ours is
    finite - never a TypeError."""
    for na in (None, "NA", float("nan")):
        _assert_es(
            {0: (1.0, 0.1), 1: (float("nan"), float("nan"))},
            {"0": [1.0, 0.1], "1": [na, na]},
        )
        # ours finite where golden is NA -> inconsistent, must fail
        with pytest.raises(AssertionError):
            _assert_es({1: (5.0, 0.1)}, {"1": [na, na]})
        # NaN-consistency: att NaN but se still finite must also fail (both must be NaN)
        with pytest.raises(AssertionError):
            _assert_es({1: (float("nan"), 0.1)}, {"1": [na, na]})


class TestLPDiDParityR:
    """Pin ``LPDiD`` against the authors' reference recipes + alexCardazzi cross-check."""

    def test_vw_event_study(self, golden: dict, panel: pd.DataFrame) -> None:
        pre, post = _window(golden)
        res = LPDiD(pre_window=pre, post_window=post, reweight=False, cluster="unit").fit(
            panel, outcome="y", unit="unit", time="time", treatment="treat"
        )
        _assert_es(_es_map(res), golden["vw_es"])

    def test_ew_reweight_event_study(self, golden: dict, panel: pd.DataFrame) -> None:
        pre, post = _window(golden)
        res = LPDiD(pre_window=pre, post_window=post, reweight=True, cluster="unit").fit(
            panel, outcome="y", unit="unit", time="time", treatment="treat"
        )
        _assert_es(_es_map(res), golden["ew_es"])

    def test_pmd_event_study(self, golden: dict, panel: pd.DataFrame) -> None:
        pre, post = _window(golden)
        res = LPDiD(pre_window=pre, post_window=post, reweight=False, pmd=2, cluster="unit").fit(
            panel, outcome="y", unit="unit", time="time", treatment="treat"
        )
        _assert_es(_es_map(res), golden["pmd_es"])

    def test_direct_covariate_event_study(self, golden: dict, panel: pd.DataFrame) -> None:
        pre, post = _window(golden)
        # Direct inclusion (reweight=False + covariates) must emit the Appendix B.2.2
        # homogeneity warning (REGISTRY ## LPDiD Deviation 3).
        with pytest.warns(UserWarning, match="direct inclusion"):
            res = LPDiD(pre_window=pre, post_window=post, reweight=False, cluster="unit").fit(
                panel, covariates=["x"], outcome="y", unit="unit", time="time", treatment="treat"
            )
        _assert_es(_es_map(res), golden["direct_es"])

    def test_pooled(self, golden: dict, panel: pd.DataFrame) -> None:
        pre, post = _window(golden)
        res = LPDiD(pre_window=pre, post_window=post, reweight=False, cluster="unit").fit(
            panel, outcome="y", unit="unit", time="time", treatment="treat"
        )
        g_post = golden["pooled"]["post"]
        assert np.isfinite(res.att) and np.isfinite(res.se)
        assert res.att == pytest.approx(g_post[0], abs=1e-6)
        assert res.se == pytest.approx(g_post[1], abs=1e-7)
        # pre pooled row
        pre_row = res.pooled.loc[res.pooled["window"] == "pre"]
        assert len(pre_row) == 1
        g_pre = golden["pooled"]["pre"]
        assert float(pre_row["coefficient"].iloc[0]) == pytest.approx(g_pre[0], abs=1e-6)
        assert float(pre_row["se"].iloc[0]) == pytest.approx(g_pre[1], abs=1e-7)

    def test_ra_covariate_point(self, golden: dict, panel: pd.DataFrame) -> None:
        """RA point estimate == authors' teffects/full-interaction point (R-anchored)."""
        pre, post = _window(golden)
        res = LPDiD(pre_window=pre, post_window=post, reweight=True, cluster="unit").fit(
            panel, covariates=["x"], outcome="y", unit="unit", time="time", treatment="treat"
        )
        _assert_es(_es_map(res), golden["ra_cov"], check_se=False)

    def test_ra_covariate_se_regression_pin(self, panel: pd.DataFrame) -> None:
        """RA influence-function SE pinned (no runnable R reference; see RA_SE_PIN).

        Calibration validated separately by benchmarks/python/coverage_lpdid_ra.py.
        """
        res = LPDiD(pre_window=3, post_window=4, reweight=True, cluster="unit").fit(
            panel, covariates=["x"], outcome="y", unit="unit", time="time", treatment="treat"
        )
        es = {int(r.horizon): float(r.se) for r in res.event_study.itertuples()}
        for h, pinned in RA_SE_PIN.items():
            assert h in es, f"missing horizon {h}"
            assert np.isfinite(es[h]) and es[h] > 0, f"h={h}: RA SE not finite/positive"
            assert es[h] == pytest.approx(pinned, abs=1e-6), f"RA SE pin drift at h={h}"
        # Headline (pooled) RA SE is the same convention - pin it too so pooled RA
        # inference drift is also caught (not just the event-study horizons).
        assert np.isfinite(res.se) and res.se > 0
        assert res.se == pytest.approx(
            POOLED_RA_SE_PIN["post"], abs=1e-6
        ), "pooled-post RA SE drift"
        pre_se = float(res.pooled.loc[res.pooled["window"] == "pre", "se"].iloc[0])
        assert pre_se == pytest.approx(POOLED_RA_SE_PIN["pre"], abs=1e-6), "pooled-pre RA SE drift"


class TestLPDiDNonAbsorbingParityR:
    """Pin the C1 non-absorbing modes against the independent feols Eq. 12/13 recipes.

    The variance-weighted variants match the feols golden on point AND SE; the
    reweighted point matches feols while its SE is a pinned regression guard
    (documented weighted-cluster convention difference). alexCardazzi's
    ``nonabsorbing_lag`` is recorded in the golden meta as a divergent reference only.
    """

    def _meta(self, na_golden: dict):
        m = na_golden["meta"]
        return int(m["L"]), int(m["pre_window"]), int(m["post_window"])

    def test_first_entry_event_study(self, na_golden: dict, na_panel: pd.DataFrame) -> None:
        L, pre, post = self._meta(na_golden)
        res = LPDiD(
            pre_window=pre, post_window=post, cluster="unit", non_absorbing="first_entry"
        ).fit(na_panel, outcome="y", unit="unit", time="time", treatment="treat", only_event=True)
        _assert_es(_es_map(res), na_golden["first_entry"])  # point + SE (feols-parity)

    def test_effect_stabilization_event_study(
        self, na_golden: dict, na_panel: pd.DataFrame
    ) -> None:
        L, pre, post = self._meta(na_golden)
        res = LPDiD(
            pre_window=pre,
            post_window=post,
            cluster="unit",
            non_absorbing="effect_stabilization",
            stabilization_window=L,
        ).fit(na_panel, outcome="y", unit="unit", time="time", treatment="treat", only_event=True)
        _assert_es(_es_map(res), na_golden["effect_stab"])  # point + SE (feols-parity)

    def test_effect_stabilization_reweighted_point(
        self, na_golden: dict, na_panel: pd.DataFrame
    ) -> None:
        """Reweighted (equally-weighted) effect_stabilization POINT == feols recipe.

        The reweighted SE is pinned separately (RW_SE_PIN) - it has a small
        weighted-cluster convention difference vs feols, not feols-parity.
        """
        L, pre, post = self._meta(na_golden)
        res = LPDiD(
            pre_window=pre,
            post_window=post,
            reweight=True,
            cluster="unit",
            non_absorbing="effect_stabilization",
            stabilization_window=L,
        ).fit(na_panel, outcome="y", unit="unit", time="time", treatment="treat", only_event=True)
        _assert_es(_es_map(res), na_golden["effect_stab_rw"], check_se=False)
        # Reweighted SE: pinned regression guard (documented feols convention diff).
        es = {int(r.horizon): float(r.se) for r in res.event_study.itertuples()}
        for h, pinned in RW_SE_PIN.items():
            assert h in es, f"missing horizon {h}"
            assert np.isfinite(es[h]) and es[h] > 0, f"h={h}: reweighted SE not finite/positive"
            assert es[h] == pytest.approx(pinned, abs=1e-6), f"reweighted SE pin drift at h={h}"

    def test_alex_recorded_as_divergent_reference(self, na_golden: dict) -> None:
        """alexCardazzi nonabsorbing_lag is recorded (meta), NOT a parity gate: it
        diverges from the paper-faithful Eq.13 even on this panel."""
        alex = na_golden["alex_nonabsorbing_lag"]
        assert "error" not in alex, f"alex reference failed to generate: {alex}"
        es = na_golden["effect_stab"]
        # At least one post horizon differs materially (off-switch clamp / boundary),
        # which is exactly why alex is documented, not gated.
        diffs = [
            abs(_num(alex[k][0]) - _num(es[k][0]))
            for k in es
            if int(k) >= 0
            and k in alex
            and np.isfinite(_num(es[k][0]))
            and np.isfinite(_num(alex[k][0]))
        ]
        assert diffs and max(diffs) > 1e-3, "expected a documented alex divergence on post horizons"
        # The divergence is NOT only off-switch handling: it persists on the monotone
        # (no-off-switch) sub-panel, recorded as committed evidence in meta.
        mono = _num(na_golden["meta"]["alex_monotone_post_divergence"])
        assert mono > 1e-3, f"expected alex to diverge from Eq.13 on the monotone slice, got {mono}"


class TestLPDiDSurveyParityR:
    """Pin the merged D1 survey path against ``survey::svyglm`` goldens (Phase D2).

    Three structurally-distinct survey variance paths are R-validated end-to-end
    through ``LPDiD.fit(survey_design=...)``:

    * **VW** — full stratified-PSU design with FPC vs ``svyglm(ids=~psu, strata,
      fpc, weights)``; reported ``n_clusters`` == n_PSU == 14, df == n_PSU - n_strata
      == 10 (constant here).
    * **inject** — weights-only, the unit injected as PSU, vs ``svyglm(ids=~unit,
      weights)``; ``n_clusters`` == n_units == 140, df == n_PSU - 1 == 139.
    * **covariate** — direct covariate inclusion vs ``svyglm(Dy ~ tr + x +
      factor(time), ...)`` (emits the Appendix B.2.2 homogeneity warning).

    Each clean LP-DiD horizon uses a FRESH ``svydesign`` over that horizon's sample,
    matching the library's per-sample ``survey_design.resolve(sample)``. The
    clean-sample construction is independently alexCardazzi-cross-checked inside the
    generator (the UNWEIGHTED VW event study matches to <1e-8); ``svyglm`` supplies the
    survey variance, so it is the reference (no separate survey package gate needed).

    Goldens (``c(estimate, SE, df, n_psu)`` per horizon / pooled row) are generated by::

        Rscript benchmarks/R/generate_lpdid_survey_golden.R

    There is no per-horizon ``df`` field in the result schema: ``event_study`` /
    ``pooled`` rows expose ``n_clusters`` (= realized n_PSU), and df is reconstructed
    with the design-specific formula (``n_clusters - n_strata`` with strata, else
    ``n_clusters - 1``). Pure-numpy survey path -> backend-agnostic.
    """

    @staticmethod
    def _fit(panel: pd.DataFrame, sd: SurveyDesign, **kw):
        # The expected per-sample survey warnings (pweight normalization, PSU/cluster
        # reconciliation) are not under test here; silence them so the parity signal is
        # clean. The covariate variant asserts its homogeneity warning explicitly.
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            return LPDiD(pre_window=3, post_window=4, reweight=False, cluster="unit").fit(
                panel,
                outcome="y",
                unit="unit",
                time="time",
                treatment="treat",
                survey_design=sd,
                **kw,
            )

    @staticmethod
    def _assert_es(res, golden_es: dict, *, strata: bool) -> None:
        """Point (``abs=1e-6``) + SE (``rtol=1e-5``/``abs=1e-7``) + n_PSU + df exact, per
        horizon. df is reconstructed from the per-horizon ``n_clusters`` (= realized
        n_PSU) with the design-specific formula."""
        rows = {int(r.horizon): r for r in res.event_study.itertuples()}
        n_strata = int(res.n_strata)
        assert golden_es, "golden variant has no horizons"
        for hk, gv in golden_es.items():
            h = int(hk)
            g_est, g_se, g_df, g_npsu = (_num(gv[i]) for i in range(4))
            assert h in rows, f"missing horizon {h}"
            row = rows[h]
            assert np.isfinite(float(row.coefficient)), f"h={h}: non-finite att"
            assert float(row.coefficient) == pytest.approx(g_est, abs=1e-6), f"att h={h}"
            assert float(row.se) == pytest.approx(g_se, rel=1e-5, abs=1e-7), f"se h={h}"
            assert int(row.n_clusters) == int(g_npsu), f"n_psu h={h}"
            df_recon = int(row.n_clusters) - (n_strata if strata else 1)
            assert df_recon == int(g_df), f"df h={h}: recon {df_recon} != golden {int(g_df)}"

    @staticmethod
    def _assert_pooled(res, golden_pooled: dict, *, strata: bool) -> None:
        n_strata = int(res.n_strata)
        g_post = golden_pooled["post"]
        # post == the headline pooled estimate
        assert np.isfinite(res.att) and np.isfinite(res.se)
        assert float(res.att) == pytest.approx(_num(g_post[0]), abs=1e-6), "pooled-post att"
        assert float(res.se) == pytest.approx(_num(g_post[1]), rel=1e-5, abs=1e-7), "pooled-post se"
        post_row = res.pooled.loc[res.pooled["window"] == "post"].iloc[0]
        # the pooled-post DataFrame row's own coefficient/se (not only the res.att/res.se
        # headline that mirrors them) so a pooled-row schema regression cannot slip past
        assert float(post_row["coefficient"]) == pytest.approx(
            _num(g_post[0]), abs=1e-6
        ), "pooled-post row att"
        assert float(post_row["se"]) == pytest.approx(
            _num(g_post[1]), rel=1e-5, abs=1e-7
        ), "pooled-post row se"
        assert int(post_row["n_clusters"]) == int(_num(g_post[3])), "pooled-post n_psu"
        df_recon = int(post_row["n_clusters"]) - (n_strata if strata else 1)
        assert df_recon == int(_num(g_post[2])), "pooled-post df"
        # pre pooled row: point/SE AND n_psu/df (the df reconstruction has teeth for the
        # inject variant where n_strata == 0)
        g_pre = golden_pooled["pre"]
        pre_row = res.pooled.loc[res.pooled["window"] == "pre"].iloc[0]
        assert float(pre_row["coefficient"]) == pytest.approx(
            _num(g_pre[0]), abs=1e-6
        ), "pooled-pre att"
        assert float(pre_row["se"]) == pytest.approx(
            _num(g_pre[1]), rel=1e-5, abs=1e-7
        ), "pooled-pre se"
